"""VMD scene: WT and mutant side by side plus a differential binding-site overlay.

The generated Tcl script also opens a 2D panel that tracks the per-frame
difference of the pocket latents (MUT - WT).
"""

from __future__ import annotations

import os
from typing import List, Optional, Sequence, Tuple

import numpy as np

from pert.structure.binding_site import binding_site_keys_from_pdb
from pert.structure.selection import ligand_selection
from pert.visualization.vmd_common import site_selection_from_keys, tcl_braced_path


def write_vmd_comparison_script(
    wt_pdb: str,
    mut_pdb: str,
    output_tcl: str,
    ligand_resnames: Sequence[str],
    wt_dcd: Optional[str] = None,
    mut_dcd: Optional[str] = None,
    site_cutoff_ang: float = 6.0,
    latents_npz: Optional[str] = None,
) -> str:
    """Write the WT-vs-MUT comparison scene (side-by-side + differential site overlay + delta-latent panel)."""
    ligand_tokens = ligand_selection(ligand_resnames)
    ligand_sel = ligand_tokens.vmd()

    delta_latent_xy: List[Tuple[float, float]] = [(0.0, 0.0)]
    if latents_npz and os.path.exists(latents_npz):
        try:
            lat = np.load(latents_npz)
            u_wt = np.asarray(lat["u_b_wt"], dtype=float)
            u_mut = np.asarray(lat["u_b_mut"], dtype=float)
            n = min(int(u_wt.shape[0]), int(u_mut.shape[0]))
            if n > 0:
                d = min(int(u_wt.shape[1]), int(u_mut.shape[1]))
                if d >= 2:
                    du = u_mut[:n, :2] - u_wt[:n, :2]
                elif d == 1:
                    du = np.column_stack([u_mut[:n, 0] - u_wt[:n, 0], np.zeros(n, dtype=float)])
                else:
                    du = np.zeros((n, 2), dtype=float)
                sx = max(float(np.max(np.abs(du[:, 0]))), 1e-8)
                sy = max(float(np.max(np.abs(du[:, 1]))), 1e-8)
                delta_latent_xy = [(float(row[0] / sx), float(row[1] / sy)) for row in du]
                if not delta_latent_xy:
                    delta_latent_xy = [(0.0, 0.0)]
        except Exception:
            delta_latent_xy = [(0.0, 0.0)]
    delta_latent_xy_tcl = " ".join(f"{{{xy[0]:.6f} {xy[1]:.6f}}}" for xy in delta_latent_xy)

    wt_site_keys = set(binding_site_keys_from_pdb(wt_pdb, ligand_tokens, site_cutoff_ang))
    mut_site_keys = set(binding_site_keys_from_pdb(mut_pdb, ligand_tokens, site_cutoff_ang))
    wt_diff_sel = site_selection_from_keys(sorted(wt_site_keys - mut_site_keys))
    mut_diff_sel = site_selection_from_keys(sorted(mut_site_keys - wt_site_keys))

    lines = [
        "# Auto-generated WT/MUT comparison view for VMD",
        "display projection Orthographic",
        "display depthcue off",
        "axes location Off",
        "color Display Background white",
        "",
        f"set wt_pdb {tcl_braced_path(wt_pdb)}",
        f"set wt_dcd {tcl_braced_path(wt_dcd)}",
        f"set mut_pdb {tcl_braced_path(mut_pdb)}",
        f"set mut_dcd {tcl_braced_path(mut_dcd)}",
        f"set ligand_sel {{{ligand_sel}}}",
        f"set site_cutoff {float(site_cutoff_ang):.3f}",
        f"set delta_latent_xy {{{delta_latent_xy_tcl}}}",
        f"set wt_diff_site_sel {{{wt_diff_sel}}}",
        f"set mut_diff_site_sel {{{mut_diff_sel}}}",
        "",
        "proc align_to_first {mid sel_text} {",
        "    set ref [atomselect $mid $sel_text frame 0]",
        "    if {[$ref num] < 3} {",
        "        $ref delete",
        "        return",
        "    }",
        "    set mob [atomselect $mid $sel_text]",
        "    set all [atomselect $mid all]",
        "    set nframes [molinfo $mid get numframes]",
        "    for {set f 0} {$f < $nframes} {incr f} {",
        "        $mob frame $f",
        "        $all frame $f",
        "        set xf [measure fit $mob $ref]",
        "        $all move $xf",
        "    }",
        "    $ref delete",
        "    $mob delete",
        "    $all delete",
        "}",
        "",
        "proc pick_alignment_selection {ref_mol mob_mol ligand_sel} {",
        "    set ref [atomselect $ref_mol \"protein and name CA\" frame 0]",
        "    set mob [atomselect $mob_mol \"protein and name CA\" frame 0]",
        "    set ok [expr {[$ref num] > 2 && [$ref num] == [$mob num]}]",
        "    $ref delete",
        "    $mob delete",
        "    if {$ok} {",
        "        return {protein and name CA}",
        "    }",
        "    if {$ligand_sel ne \"none\"} {",
        "        set ref [atomselect $ref_mol \"($ligand_sel) and not hydrogen\" frame 0]",
        "        set mob [atomselect $mob_mol \"($ligand_sel) and not hydrogen\" frame 0]",
        "        set ok [expr {[$ref num] > 2 && [$ref num] == [$mob num]}]",
        "        $ref delete",
        "        $mob delete",
        "        if {$ok} {",
        "            return \"($ligand_sel) and not hydrogen\"",
        "        }",
        "    }",
        "    return {}",
        "}",
        "",
        "proc fit_mobile_to_ref_per_frame {ref_mol mob_mol ligand_sel} {",
        "    set sel [pick_alignment_selection $ref_mol $mob_mol $ligand_sel]",
        "    if {$sel eq \"\"} {",
        "        return",
        "    }",
        "    set nref [molinfo $ref_mol get numframes]",
        "    set nmob [molinfo $mob_mol get numframes]",
        "    set nframes [expr {$nref < $nmob ? $nref : $nmob}]",
        "    for {set f 0} {$f < $nframes} {incr f} {",
        "        set ref [atomselect $ref_mol $sel frame $f]",
        "        set mob [atomselect $mob_mol $sel frame $f]",
        "        if {[$ref num] > 2 && [$ref num] == [$mob num]} {",
        "            set xf [measure fit $mob $ref]",
        "            set all [atomselect $mob_mol all]",
        "            $all frame $f",
        "            $all move $xf",
        "            $all delete",
        "        }",
        "        $ref delete",
        "        $mob delete",
        "    }",
        "}",
        "",
        "proc load_system_view {pdb_path dcd_path ligand_sel site_cutoff site_sel_text prot_color lig_color site_color prot_material site_material site_rad show_protein mol_name} {",
        "    mol new $pdb_path type pdb waitfor all",
        "    set mid [molinfo top]",
        "    if {[string length $dcd_path] > 0 && [file exists $dcd_path]} {",
        "        mol addfile $dcd_path type dcd waitfor all molid $mid",
        "    }",
        "    align_to_first $mid {protein and name CA}",
        "    mol rename $mid $mol_name",
        "    mol delrep 0 $mid",
        "",
        "    if {$show_protein > 0} {",
        "        mol representation NewCartoon 0.24 20.0 4.1 0",
        "        mol color ColorID $prot_color",
        "        mol selection {protein}",
        "        mol material $prot_material",
        "        mol addrep $mid",
        "    }",
        "",
        "    mol representation Licorice 0.20 18.0 18.0",
        "    mol color ColorID $lig_color",
        "    mol selection $ligand_sel",
        "    mol material Glossy",
        "    mol addrep $mid",
        "",
        "    if {$site_sel_text ne \"none\"} {",
        "        mol representation QuickSurf $site_rad 0.6 1.0 1.0",
        "        mol color ColorID $site_color",
        "        mol selection $site_sel_text",
        "        mol material $site_material",
        "        mol addrep $mid",
        "    }",
        "",
        "    return $mid",
        "}",
        "",
        "set wt_side [load_system_view $wt_pdb $wt_dcd $ligand_sel $site_cutoff {none} 6 4 10 AOShiny Transparent 1.0 1 WT_SIDE]",
        "set mut_side [load_system_view $mut_pdb $mut_dcd $ligand_sel $site_cutoff {none} 1 3 9 AOShiny Transparent 1.0 1 MUT_SIDE]",
        "fit_mobile_to_ref_per_frame $wt_side $mut_side $ligand_sel",
        "",
        "set wt_all [atomselect $wt_side all]",
        "$wt_all moveby {-18.0 0.0 0.0}",
        "$wt_all delete",
        "set mut_all [atomselect $mut_side all]",
        "$mut_all moveby {18.0 0.0 0.0}",
        "$mut_all delete",
        "",
        "set wt_overlay [load_system_view $wt_pdb $wt_dcd $ligand_sel $site_cutoff $wt_diff_site_sel 10 4 10 Transparent Transparent 1.0 0 WT_OVERLAY]",
        "set mut_overlay [load_system_view $mut_pdb $mut_dcd $ligand_sel $site_cutoff $mut_diff_site_sel 3 3 27 Transparent Transparent 1.22 0 MUT_OVERLAY]",
        "fit_mobile_to_ref_per_frame $wt_overlay $mut_overlay $ligand_sel",
        "",
        "set wt_overlay_all [atomselect $wt_overlay all]",
        "$wt_overlay_all moveby {0.0 0.0 0.0}",
        "$wt_overlay_all delete",
        "set mut_overlay_all [atomselect $mut_overlay all]",
        "$mut_overlay_all moveby {0.0 0.0 0.0}",
        "$mut_overlay_all delete",
        "",
        "mol top $wt_side",
        "",
        "proc _clip01 {x} {",
        "    if {$x < 0.0} { return 0.0 }",
        "    if {$x > 1.0} { return 1.0 }",
        "    return $x",
        "}",
        "",
        "proc _delta_time_color {t} {",
        "    set tt [_clip01 $t]",
        "    set r [expr {int(56 + 184 * $tt)}]",
        "    set g [expr {int(136 + 10 * $tt)}]",
        "    set b [expr {int(192 - 150 * $tt)}]",
        "    return [format \"#%02x%02x%02x\" $r $g $b]",
        "}",
        "",
        "proc _delta_canvas_xy {dx dy} {",
        "    set w 560",
        "    set h 420",
        "    set m 58",
        "    set x [expr {$w / 2.0 + $dx * (($w / 2.0) - $m)}]",
        "    set y [expr {$h / 2.0 - $dy * (($h / 2.0) - $m)}]",
        "    return [list $x $y]",
        "}",
        "",
        "proc setup_delta_latent_window {} {",
        "    global delta_latent_xy delta_canvas delta_marker delta_frame_text delta_mag_text delta_ready",
        "    set delta_ready 0",
        "    if {[catch {",
        "        if {[winfo exists .delta2d]} { destroy .delta2d }",
        "        toplevel .delta2d",
        "        wm title .delta2d {WT vs MUT Delta Latent Map}",
        "        wm geometry .delta2d 560x420+700+80",
        "        canvas .delta2d.c -width 560 -height 420 -background #f5f9ff -highlightthickness 0",
        "        pack .delta2d.c -fill both -expand 1",
        "    } err]} {",
        "        puts [format {Delta latent window unavailable: %s} $err]",
        "        return",
        "    }",
        "    set c .delta2d.c",
        "    set delta_canvas $c",
        "    set w 560",
        "    set h 420",
        "    set m 58",
        "    for {set i 0} {$i <= 6} {incr i} {",
        "        set x [expr {$m + $i * ($w - 2.0 * $m) / 6.0}]",
        "        set y [expr {$m + $i * ($h - 2.0 * $m) / 6.0}]",
        "        $c create line $x $m $x [expr {$h - $m}] -fill #d8e3f2 -width 1",
        "        $c create line $m $y [expr {$w - $m}] $y -fill #d8e3f2 -width 1",
        "    }",
        "    $c create line $m [expr {$h / 2.0}] [expr {$w - $m}] [expr {$h / 2.0}] -fill #607992 -width 2",
        "    $c create line [expr {$w / 2.0}] $m [expr {$w / 2.0}] [expr {$h - $m}] -fill #607992 -width 2",
        "    $c create text [expr {$w / 2.0}] 20 -text {Delta Latent Map (MUT - WT)} -font {Helvetica 15 bold} -fill #17324d",
        "    $c create text [expr {$w / 2.0}] 42 -text {Center = no difference; farther = larger difference} -font {Helvetica 10 italic} -fill #47657f",
        "    $c create text [expr {$w / 2.0}] [expr {$h - 20}] -text {Delta axis 1} -font {Helvetica 11} -fill #17324d",
        "    $c create text 24 [expr {$h / 2.0}] -text {Delta axis 2} -angle 90 -font {Helvetica 11} -fill #17324d",
        "    set n [llength $delta_latent_xy]",
        "    for {set i 1} {$i < $n} {incr i} {",
        "        set p0 [lindex $delta_latent_xy [expr {$i - 1}]]",
        "        set p1 [lindex $delta_latent_xy $i]",
        "        lassign [_delta_canvas_xy [lindex $p0 0] [lindex $p0 1]] x0 y0",
        "        lassign [_delta_canvas_xy [lindex $p1 0] [lindex $p1 1]] x1 y1",
        "        set t [expr {$i / double(max($n - 1, 1))}]",
        "        $c create line $x0 $y0 $x1 $y1 -fill [_delta_time_color $t] -width 2",
        "    }",
        "    set p_init [lindex $delta_latent_xy 0]",
        "    lassign [_delta_canvas_xy [lindex $p_init 0] [lindex $p_init 1]] x y",
        "    set delta_marker [$c create oval [expr {$x - 8}] [expr {$y - 8}] [expr {$x + 8}] [expr {$y + 8}] -fill #2563eb -outline #0f172a -width 2]",
        "    set delta_frame_text [$c create text [expr {$w - 102}] 20 -text {Frame 0} -font {Helvetica 11 bold} -fill #17324d]",
        "    set delta_mag_text [$c create text [expr {$w - 108}] 42 -text {Delta 0.00} -font {Helvetica 10} -fill #2f4b69]",
        "    set delta_ready 1",
        "}",
        "",
        "proc update_delta_latent_window {frame} {",
        "    global delta_latent_xy delta_canvas delta_marker delta_frame_text delta_mag_text delta_ready",
        "    if {![info exists delta_ready] || !$delta_ready} { return }",
        "    if {![winfo exists .delta2d] || ![winfo exists $delta_canvas]} {",
        "        set delta_ready 0",
        "        return",
        "    }",
        "    set n [llength $delta_latent_xy]",
        "    if {$n < 1} { return }",
        "    set idx $frame",
        "    if {$idx < 0} { set idx 0 }",
        "    if {$idx >= $n} { set idx [expr {$n - 1}] }",
        "    set p [lindex $delta_latent_xy $idx]",
        "    set dx [lindex $p 0]",
        "    set dy [lindex $p 1]",
        "    lassign [_delta_canvas_xy $dx $dy] x y",
        "    $delta_canvas coords $delta_marker [expr {$x - 8}] [expr {$y - 8}] [expr {$x + 8}] [expr {$y + 8}]",
        "    set mag [expr {sqrt($dx*$dx + $dy*$dy)}]",
        "    set tt [expr {$idx / double(max($n - 1, 1))}]",
        "    $delta_canvas itemconfigure $delta_marker -fill [_delta_time_color $tt]",
        "    $delta_canvas itemconfigure $delta_frame_text -text [format {Frame %d/%d} $idx [expr {$n - 1}]]",
        "    $delta_canvas itemconfigure $delta_mag_text -text [format {Delta %.2f} $mag]",
        "}",
        "",
        "proc sync_comparison_frames {name index op} {",
        "    global wt_side mut_side wt_overlay mut_overlay",
        "    if {[catch {set f [molinfo $wt_side get frame]}]} {",
        "        return",
        "    }",
        "    foreach m [list $mut_side $wt_overlay $mut_overlay] {",
        "        if {[catch {set nf [molinfo $m get numframes]}]} {",
        "            continue",
        "        }",
        "        if {$nf < 1} {",
        "            continue",
        "        }",
        "        set ff $f",
        "        if {$ff >= $nf} {",
        "            set ff [expr {$nf - 1}]",
        "        }",
        "        molinfo $m set frame $ff",
        "    }",
        "    update_delta_latent_window $f",
        "}",
        "proc poll_delta_sync {} {",
        "    global wt_side",
        "    if {[catch {set f [molinfo $wt_side get frame]}]} {",
        "        after 80 poll_delta_sync",
        "        return",
        "    }",
        "    sync_comparison_frames _ _ _",
        "    after 80 poll_delta_sync",
        "}",
        "setup_delta_latent_window",
        "catch {trace remove variable vmd_frame($wt_side) write sync_comparison_frames}",
        "trace add variable vmd_frame($wt_side) write sync_comparison_frames",
        "after 80 poll_delta_sync",
        "",
        "animate style Loop",
        "animate speed 0.7",
        "animate goto 0",
        "sync_comparison_frames _ _ _",
        "after 200 {animate forward}",
        "display resetview",
        "puts \"Loaded WT/MUT comparison.\"",
        "puts \"Left: WT (blue). Right: MUT (red). Center: WT/MUT transparent overlay.\"",
        "puts \"All views are aligned frame-by-frame before comparison.\"",
        "puts \"Delta Latent window shows (MUT-WT) trajectory; moving dot follows current frame.\"",
        "puts \"Center in Delta Latent means similar states; larger distance means stronger divergence.\"",
        "puts \"Center view shows only differential shells: WT-only (cyan) and MUT-only (purple).\"",
    ]
    os.makedirs(os.path.dirname(output_tcl) or ".", exist_ok=True)
    with open(output_tcl, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    return output_tcl
